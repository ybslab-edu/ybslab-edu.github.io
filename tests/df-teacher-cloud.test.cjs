  assert.match(get('#drawer').innerHTML,/&lt;img/);
  ctx.raw={...raw,cls:701,seat:1};
  vm.runInContext("ingestReport(raw,{source:'本機檔案',file:'synthetic.html'});render();",ctx);
  assert.equal(vm.runInContext('R.size',ctx),2);
